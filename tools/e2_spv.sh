#!/bin/sh
# Regenerate src/e2_gpu_spv.h from the OpenCL C kernels in tools/gpu/*.cl.
# Requires clang (SPIR-V target) and xxd.  The generated header is checked in,
# so `make` itself does not need clang/xxd.
set -e

CLANG="${CLANG:-clang}"
OUT=src/e2_gpu_spv.h
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

{
    echo "/* Auto-generated by tools/e2_spv.sh. Do not edit. */"
    echo "#ifndef E2_GPU_SPV_H"
    echo "#define E2_GPU_SPV_H"
    echo ""
    echo "#include <stddef.h>"
} > "$OUT"

# The DPAS kernels use Intel's int8 matrix-multiply builtin, which only IGC's
# own OpenCL frontend (ocloc) knows how to lower.  Everything else goes through
# clang.  Both end up as plain SPIR-V, which the Level Zero module builder
# accepts (IGC resolves the builtin when it compiles the module).
OCLOC_DEVICE=${OCLOC_DEVICE:-arl-h}

for f in tools/gpu/*.cl; do
    name=$(basename "$f" .cl)
    arr="e2_gpu_spv_${name}"
    # only a real call counts: e2_dpas.cl is the one file that needs ocloc
    # (the Intel matrix builtin), and comments mention it too.
    if sed -e "s://.*::" -e "s:/\*.*\*/::" "$f" | grep -v "^[[:space:]]*\*" |
        grep -q "intel_sub_group_"; then
        mkdir -p "$TMP/$name"
        ocloc compile -file "$f" -device "$OCLOC_DEVICE" -out_dir "$TMP/$name" \
            -output "$name" >/dev/null
        cp "$TMP/$name/${name}_"*.spv "$TMP/$name.spv"
    else
        "$CLANG" -target spirv64-unknown-unknown -x cl -cl-std=CL3.0 -O2 -c "$f" \
            -o "$TMP/$name.spv"
    fi
    xxd -i "$TMP/$name.spv" > "$TMP/$name.inc"
    sed -e "s/^unsigned char .*\[\]/static const unsigned char ${arr}[]/" \
        -e "s/^unsigned int .*_len/static const size_t ${arr}_len/" \
        "$TMP/$name.inc" >> "$OUT"
    echo "" >> "$OUT"
done

echo "#endif /* E2_GPU_SPV_H */" >> "$OUT"
echo "wrote $OUT"
